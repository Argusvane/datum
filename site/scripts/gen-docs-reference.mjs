// Writes the docs site's element reference tables from the elements' own attribute list
// (../docs/reference/attributes.json, itself generated from the elements' code). The tables land in
// docs/_generated/ as partials the reference pages include, so a page's words are written by hand and
// its tables never drift from the code.
//
//   node scripts/gen-docs-reference.mjs           write the partials
//   node scripts/gen-docs-reference.mjs --check   fail when a partial is stale

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../../docs/reference/attributes.json", import.meta.url);
const outDir = new URL("../docs/_generated/", import.meta.url);

/** The partial each element's tables are named by. */
export const ELEMENT_SLUGS = {
  "datum-form": "form",
  "datum-form-builder": "builder"
};

/**
 * A note as the site prints it: the reference cites the repository's decision records, which the
 * site never does, and its text goes into a Markdown table inside a Vue template.
 */
export function siteText(text) {
  const cleaned = String(text)
    .replace(/\s*\(ADR \d{4}\)/g, "")
    .replace(/\(ADR \d{4}[:;] /g, "(")
    .replace(/, ADR \d{4}\)/g, ")")
    .replace(/\s+/g, " ")
    .trim();
  if (/ADR|QuickJS/i.test(cleaned)) throw new Error(`a note still names what the site does not: ${cleaned}`);
  if (cleaned.includes("{{")) throw new Error(`a note would be read as a template: ${cleaned}`);
  return cleaned.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/\|/g, "\\|");
}

const code = (name) => `\`${name}\``;
const header = "<!-- Generated by scripts/gen-docs-reference.mjs from docs/reference/attributes.json. Do not edit. -->\n\n";

/**
 * A table of two columns, the name and what it does: a note is a paragraph, so it gets the width,
 * and what an attribute takes and defaults to are the last line of its cell. The wrapper is what
 * the theme's stylesheet keeps the name column to one line by.
 */
const table = (head, lines) => `${header}<div class="ref-table">\n\n${[head, "|---|---|", ...lines].join("\n")}\n\n</div>\n`;

function attributesTable(rows) {
  return table(
    "| Attribute and property | What it does |",
    rows.map((row) => {
      // An attribute and property of one spelling are named once.
      const property = /^\(/.test(row.prop) ? "<br>attribute only" : row.prop === row.attribute ? "" : `<br>${code(row.prop)}`;
      return `| ${code(row.attribute)}${property} | ${siteText(row.notes)}<br>**Takes** ${siteText(row.values)}. **Default** ${siteText(row.default)}. |`;
    })
  );
}

function propertiesTable(rows) {
  return table("| Property | What it is |", rows.map((row) => `| ${row.prop.split(/,\s*/).map(code).join("<br>")} | ${siteText(row.notes)} |`));
}

function eventsTable(rows) {
  return table("| Event | When, and what `detail` carries |", rows.map((row) => `| ${code(row.name)} | ${siteText(row.description)} |`));
}

/** Every partial, by file name. */
export function partials(reference = JSON.parse(readFileSync(source, "utf8"))) {
  const files = {};
  for (const [element, slug] of Object.entries(ELEMENT_SLUGS)) {
    const attributes = reference.elements[element];
    if (!attributes) throw new Error(`attributes.json has no ${element}`);
    files[`${slug}-attributes.md`] = attributesTable(attributes);
    const properties = reference.jsOnly.filter((row) => row.element === element);
    if (properties.length > 0) files[`${slug}-properties.md`] = propertiesTable(properties);
    const events = reference.events[element];
    if (events) files[`${slug}-events.md`] = eventsTable(events);
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = [];
  mkdirSync(outDir, { recursive: true });
  for (const [name, text] of Object.entries(partials())) {
    const file = new URL(name, outDir);
    const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
    if (current === text) continue;
    if (check) stale.push(name);
    else writeFileSync(file, text);
  }
  if (stale.length > 0) {
    console.error(`Stale: ${stale.join(", ")}. Run npm run docs:reference in site/.`);
    process.exit(1);
  }
}
