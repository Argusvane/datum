#!/usr/bin/env node
// Lives in integrations/shared because it writes more than one host's pin: quickjs-ng's qjs-wasi.wasm,
// pinned by the sha256 digest GitHub publishes for the release asset. Only the official repository is
// read (quickjs-ng/quickjs). Review the diff before committing.
//
// --target jvm|fastapi|all (default jvm) picks what is rewritten. The JVM hosts (integrations/jvm) read the release and rewrite
// the qjs.* properties between the `datum:qjs begin` and `datum:qjs end` comments of
// integrations/jvm/libs/datum-sandbox-endive/pom.xml.
//
//   npm run jvm:pin-runtime -- v0.16.2             (the one positional tag is quickjs-ng's)
//   node integrations/shared/scripts/pin-runtime.mjs --target all v0.16.2
//
// --target fastapi is the Python host's pin: it writes
// integrations/fastapi/packages/argusvane-datum-qjs-wasm/src/datum_qjs_wasm/runtime.json (url, sha256, size), which
// integrations/fastapi/scripts/fetch-runtime.mjs verifies the downloaded qjs-wasi.wasm against.
//
//   npm run fastapi:pin-runtime -- v0.16.2
//
// --dry-run reads the release and prints what would be written, writing nothing (the check mode the
// closing proof uses; it still needs the network).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
let target = "jvm";
const positional = [];
let dryRun = false;
for (let index = 0; index < args.length; index += 1) {
  const arg = args[index];
  if (arg === "--dry-run") {
    dryRun = true;
  } else if (arg === "--target") {
    target = args[(index += 1)] ?? "";
  } else if (arg.startsWith("--target=")) {
    target = arg.slice("--target=".length);
  } else {
    positional.push(arg);
  }
}
if (!["jvm", "fastapi", "all"].includes(target)) {
  console.error(`pin-runtime: --target must be jvm, fastapi or all (got "${target}")`);
  process.exit(1);
}
// Every target takes the quickjs tag alone.
const qjsTag = positional[0] ?? "v0.16.2";
const fastapiPin = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "fastapi", "packages", "argusvane-datum-qjs-wasm", "src", "datum_qjs_wasm", "runtime.json");
const jvmPom = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "jvm", "libs", "datum-sandbox-endive", "pom.xml");

async function release(repo, tag) {
  const response = await fetch(`https://api.github.com/repos/${repo}/releases/tags/${tag}`, {
    headers: { accept: "application/vnd.github+json", "user-agent": "datum-pin-runtime" }
  });
  if (!response.ok) {
    throw new Error(`${repo} ${tag}: HTTP ${response.status}`);
  }
  return response.json();
}

function sha256Of(asset) {
  const digest = asset.digest ?? "";
  if (!digest.startsWith("sha256:")) {
    throw new Error(`${asset.name}: the release publishes no sha256 digest`);
  }
  return digest.slice("sha256:".length);
}

const qjs = await release("quickjs-ng/quickjs", qjsTag);
const qjsAsset = qjs.assets.find((candidate) => candidate.name === "qjs-wasi.wasm");
if (!qjsAsset) {
  throw new Error(`${qjsTag}: no qjs-wasi.wasm asset`);
}

if (target === "jvm" || target === "all") {
  const begin = "<!-- datum:qjs begin";
  const end = "<!-- datum:qjs end -->";
  const pom = readFileSync(jvmPom, "utf8");
  const from = pom.indexOf(begin);
  const to = pom.indexOf(end);
  if (from < 0 || to < from) {
    throw new Error(`${jvmPom}: the datum:qjs begin/end marker comments are missing`);
  }
  const beginLineEnd = pom.indexOf("\n", from);
  const block = [
    `    <qjs.version>${qjsTag.replace(/^v/, "")}</qjs.version>`,
    `    <qjs.sha256>${sha256Of(qjsAsset)}</qjs.sha256>`,
    `    <qjs.size>${qjsAsset.size}</qjs.size>`
  ].join("\n");
  if (!dryRun) {
    writeFileSync(jvmPom, `${pom.slice(0, beginLineEnd + 1)}${block}\n    ${pom.slice(to)}`);
  }
  console.log(`pin-runtime: qjs ${qjsTag} → ${jvmPom}${dryRun ? " (dry run, nothing written)" : ""}`);
}

if (target === "fastapi" || target === "all") {
  const pin = {
    "//": "Generated by integrations/shared/scripts/pin-runtime.mjs --target fastapi from the quickjs-ng release; do not edit by hand.",
    qjsVersion: qjsTag.replace(/^v/, ""),
    asset: qjsAsset.name,
    url: qjsAsset.browser_download_url,
    sha256: sha256Of(qjsAsset),
    size: qjsAsset.size
  };
  if (!dryRun) {
    mkdirSync(dirname(fastapiPin), { recursive: true });
    writeFileSync(fastapiPin, `${JSON.stringify(pin, null, 2)}\n`);
  }
  console.log(`pin-runtime: qjs ${qjsTag} → ${fastapiPin}${dryRun ? " (dry run, nothing written)" : ""}`);
}
