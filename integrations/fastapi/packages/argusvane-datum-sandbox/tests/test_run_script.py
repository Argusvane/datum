MODULES = [RuleModule("a", "1", "({ validators: [] })"), RuleModule("b", "2", "({})")]


def test_order_capture_delete_freeze_started_register() -> None:
    snippet = freeze_snippet()
    check_order(run_script(snippet, MODULES), snippet)


def check_order(script: str, snippet: str) -> None:
    """Assert the order capture < delete < freeze < started < register < answer of one run.js."""
    lines = script.split("\n")
    snippet_lines = snippet.rstrip("\n").split("\n")
    first = lines.index(snippet_lines[0])
    # The snippet appears once, whole and unchanged, as consecutive lines.
    assert lines[first : first + len(snippet_lines)] == snippet_lines
    assert script.count(snippet.rstrip("\n")) == 1

    def at(text: str) -> int:
        found = [n for n, line in enumerate(lines) if line == text]
        assert len(found) == 1, text
        return found[0]

    capture_entry = at("  var entry = globalThis.__datum_run;")
    capture_register = at("  var register = globalThis.__datum_register;")
    delete = at("    delete globalThis[name];")
    started = at('  print(mark("started"));')
    registers = [n for n, line in enumerate(lines) if line.startswith("  register(evaluate(")]
    answer = at("  var answer = entry(input);")
    begin = at('  print(mark("begin"));')
    printed = at("  print(answer);")
    end = at('  print(mark("end"));')
    assert lines[0] == "(function (std, print, evaluate) {"  # std, print and eval captured as parameters
    assert lines[-2] == "})(std, print, eval);"
    assert capture_entry < capture_register < delete < first
    assert first + len(snippet_lines) <= started < registers[0] < registers[1] < answer < begin < printed < end


def _move(script: str, line: str, before: str) -> str:
    """Move the one line `line` to just before the first line starting with `before`."""
    lines = script.split("\n")
    lines.remove(line)
    at = next(n for n, text in enumerate(lines) if text.startswith(before))
    return "\n".join([*lines[:at], line, *lines[at:]])


def _drop_snippet(script: str, snippet: str) -> str:
    return script.replace(snippet.rstrip("\n") + "\n", "", 1)


MUTANTS: dict[str, Callable[[str, str], str]] = {
    "started before the delete": lambda s, _: _move(s, '  print(mark("started"));', '  ["std"'),
    "entry captured after the delete": lambda s, _: _move(s, "  var entry = globalThis.__datum_run;", "  var mark"),
    "register captured after the freeze": lambda s, _: _move(
        s, "  var register = globalThis.__datum_register;", "  var mark"
    ),
    "a module registered before started": lambda s, _: _move(
        s, next(line for line in s.split("\n") if line.startswith("  register(evaluate(")), '  print(mark("started"))'
    ),
    "the freeze dropped": _drop_snippet,
    "the frame printed before the answer": lambda s, _: _move(s, '  print(mark("begin"));', "  var answer"),
    "eval not captured": lambda s, _: s.replace(
        "})(std, print, eval);", "})(std, print, function (t) { return eval(t); });"
    ),
}


@pytest.mark.parametrize("mutant", MUTANTS, ids=list(MUTANTS))
def test_a_mutated_run_js_fails_the_order_check(mutant: str) -> None:
    snippet = freeze_snippet()
    script = run_script(snippet, MODULES)
    mutated = MUTANTS[mutant](script, snippet)
    assert mutated != script, mutant
    with pytest.raises((AssertionError, ValueError)):
        check_order(mutated, snippet)


