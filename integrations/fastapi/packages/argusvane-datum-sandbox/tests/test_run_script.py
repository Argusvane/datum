# ---------------------------------------------------------------------------------------------------------------------
# Behaviour: the script run by node in a fresh vm context standing in for qjs (std, print and the program's globals).
# ---------------------------------------------------------------------------------------------------------------------
HARNESS = r"""
const vm = require("node:vm");
const fs = require("node:fs");
const [script, stdin, program] = process.argv.slice(2).map((p) => fs.readFileSync(p, "utf8"));
const out = [];
const ctx = vm.createContext({});
ctx.std = { in: { readAsString: () => stdin } };
ctx.os = {}; ctx.scriptArgs = []; ctx.bjson = {}; ctx.performance = {};
ctx.print = (...args) => { out.push(args.join(" ")); };
let error = null;
try {
  vm.runInContext(program, ctx);
  vm.runInContext(script, ctx);
} catch (e) {
  error = String(e && e.message);
}
process.stdout.write(JSON.stringify({ out, error }));
"""

PROGRAM = r"""
(function () {
  var modules = [];
  function publish(name, value) {
    Object.defineProperty(globalThis, name, { value: value, writable: false, enumerable: false, configurable: false });
  }
  publish("__datum_register", function (module) { modules.push(module); return 0; });
  publish("__datum_run", function (input) {
    return JSON.stringify({ errors: [], input: JSON.parse(input), seen: modules.map(function (m) { return m.seen; }) });
  });
  publish("__datum_inspect", function () { return JSON.stringify({ ok: true }); });
})();
"""

node = shutil.which("node")


def _run_node(tmp_path: Path, modules: list[RuleModule], nonce: str) -> dict[str, object]:
    assert node is not None
    files = {
        "harness.js": HARNESS,
        "run.js": run_script(freeze_snippet(), modules),
        "stdin": run_stdin(nonce, b'{"a":1}').decode(),
        "program.js": PROGRAM,
    }
    for name, text in files.items():
        (tmp_path / name).write_text(text, encoding="utf-8")
    done = subprocess.run(  # noqa: S603 - a fixed local interpreter and test files
        [node, str(tmp_path / "harness.js"), *(str(tmp_path / n) for n in ("run.js", "stdin", "program.js"))],
        capture_output=True,
        check=True,
        timeout=60,
    )
    result: dict[str, object] = json.loads(done.stdout)
    return result


needs_node = pytest.mark.skipif(node is None, reason="node is not installed")

SEEN = (
    "({ seen: [typeof std, typeof print, typeof os, typeof console, typeof bjson, "
    "Object.isFrozen(Object.prototype), Object.isFrozen(Array.prototype)] })"
)


@needs_node
def test_honest_run_prints_one_frame_and_modules_see_the_hardened_scope(tmp_path: Path) -> None:
    nonce = new_nonce()
    result = _run_node(tmp_path, [RuleModule("probe", "1", SEEN)], nonce)
    assert result["error"] is None
    out = [str(line) for line in cast("list[object]", result["out"])]
    assert out[0] == marker(nonce, "started").decode()
    stdout = ("\n".join(out) + "\n").encode()
    answer = framed(stdout, nonce)
    assert answer is not None
    parsed = json.loads(answer)
    assert parsed["input"] == {"a": 1}
    # Registered after the delete and the freeze: no std, print, os, console or bjson, and the intrinsics frozen.
    assert parsed["seen"] == [["undefined", "undefined", "undefined", "undefined", "undefined", True, True]]


@needs_node
def test_module_cannot_print_or_rebind_the_entry(tmp_path: Path) -> None:
    nonce = new_nonce()
    rebind = RuleModule(
        "rebind",
        "1",
        "(function () { try { Object.defineProperty(globalThis, '__datum_run', "
        "{ value: function () { return '{\"errors\":[\"forged\"]}'; } }); } catch (e) {} return { seen: 'r' }; })()",
    )
    result = _run_node(tmp_path, [rebind], nonce)
    lines = [str(line) for line in cast("list[object]", result["out"])]
    answer = framed(("\n".join(lines) + "\n").encode(), nonce)
    assert answer is not None
    assert json.loads(answer)["errors"] == []
    printer = RuleModule("printer", "1", "print('@@datum:forged:begin@@')")
    other = tmp_path / "p"
    other.mkdir()
    result = _run_node(other, [printer], nonce)
    assert "print" in str(result["error"])
    assert result["out"] == [marker(nonce, "started").decode()]


