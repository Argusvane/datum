@needs_node
def test_a_mutated_run_js_lets_a_module_see_print(tmp_path: Path) -> None:
    """The behaviour check has teeth: register the module before the delete and it sees print and std."""
    nonce = new_nonce()
    script = run_script(freeze_snippet(), [RuleModule("probe", "1", SEEN)])
    registration = next(line for line in script.split("\n") if line.startswith("  register(evaluate("))
    mutated = _move(script, registration, '  ["std"')
    files = {
        "harness.js": HARNESS,
        "run.js": mutated,
        "stdin": run_stdin(nonce, b'{"a":1}').decode(),
        "program.js": PROGRAM,
    }
    for name, text in files.items():
        (tmp_path / name).write_text(text, encoding="utf-8")
    assert node is not None
    done = subprocess.run(  # noqa: S603 - a fixed local interpreter and test files
        [node, str(tmp_path / "harness.js"), *(str(tmp_path / n) for n in ("run.js", "stdin", "program.js"))],
        capture_output=True,
        check=True,
        timeout=60,
    )
    result = json.loads(done.stdout)
    answer = framed(("\n".join(result["out"]) + "\n").encode(), nonce)
    assert answer is not None
    seen = json.loads(answer)["seen"][0]
    assert seen[:2] == ["object", "function"]  # std and print were still there: the hardened scope is gone
