def freeze_snippet() -> str:
    """The engine's FREEZE_INTRINSICS_SNIPPET as argusvane-datum-programs ships it (generated by the asset script)."""
    return (resources.files("datum_programs") / "resources" / "freeze-intrinsics.js").read_text(encoding="utf-8")


def _js_literal(token: str) -> str:
    """Decode one JavaScript string literal of the snippet's array (single or double quoted, simple escapes only)."""
    quote = token[0]
    assert quote in "'\"", token
    assert token[-1] == quote, token
    out: list[str] = []
    body = token[1:-1]
    i = 0
    while i < len(body):
        char = body[i]
        if char == "\\":
            nxt = body[i + 1]
            out.append({"n": "\n", "t": "\t", "\\": "\\", "'": "'", '"': '"'}[nxt])
            i += 2
            continue
        assert char != quote, token
        out.append(char)
        i += 1
    return "".join(out)


def engine_export() -> str:
    """FREEZE_INTRINSICS_SNIPPET read from the engine's TypeScript: the array's literals joined with line feeds."""
    assert ENGINE_SOURCE is not None
    text = ENGINE_SOURCE.read_text(encoding="utf-8")
    start = text.index("export const FREEZE_INTRINSICS_SNIPPET = [")
    stop = text.index('].join("\\n");', start)
    lines: list[str] = []
    for raw in text[start:stop].splitlines()[1:]:
        item = raw.strip()
        if not item or item.startswith("//"):
            continue
        lines.append(_js_literal(item.removesuffix(",")))
    return "\n".join(lines)


