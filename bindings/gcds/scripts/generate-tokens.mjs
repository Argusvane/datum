#!/usr/bin/env node
// Cuts the token contract from what the package reads:
//   tokens.json              every custom property src/, print/ and pdf/ read through var(), with the unit the pinned release writes it in
//   pdf/tokens.generated.ts  the value of each token pdf/theme.ts reads, resolved against the release's CSS
// Values come from the pinned release's own CSS (the gcds-tokens alias); nothing is typed by hand
// except `inferred` in tokens.json, which is kept as it is. Run after a release change or a new
// var(); `kit:check`'s tokens step then keeps the contract honest (read but unlisted, listed but
// unread, undeclared, wrong unit).
//   node scripts/generate-tokens.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { unitOf } from "../../../packages/datum/binding-kit/lib/token-units.mjs";
import { declarationsOf, varsUsed } from "../../../packages/datum/binding-kit/tokens.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const GENERATED_FROM = { package: "@gcds-core/tokens", version: "1.6.0" };
const alias = Object.keys(manifest.devDependencies).find((name) => manifest.devDependencies[name] === `npm:${GENERATED_FROM.package}@${GENERATED_FROM.version}`);
if (!alias) throw new Error("package.json pins no alias for the tokens release");

const css = (dir) => readdirSync(dir).flatMap((name) => (statSync(join(dir, name)).isDirectory() ? css(join(dir, name)) : name.endsWith(".css") ? [readFileSync(join(dir, name), "utf8")] : []));
const declared = {};
for (const text of css(join(root, "node_modules", alias))) Object.assign(declared, declarationsOf(text));

/** A declared value with var() references followed through the release's own declarations. */
const resolve = (value, depth = 0) => {
  const ref = /^var\(\s*(--[\w-]+)\s*(?:,[^)]*)?\)$/.exec(value.trim());
  return ref && declared[ref[1]] !== undefined && depth < 6 ? resolve(declared[ref[1]], depth + 1) : value.trim();
};
/** The value without the trailing comment the release's CSS carries after the declaration. */
const clean = (value) => value.replace(/\/\*.*$/, "").trim();

const files = (folder) => {
  const dir = join(root, folder);
  try {
    return readdirSync(dir).filter((name) => /\.(ts|mjs|js)$/.test(name) && !name.endsWith(".generated.ts")).map((name) => join(dir, name));
  } catch {
    return [];
  }
};
const used = new Set();
for (const file of ["src", "print", "pdf"].flatMap(files)) for (const name of varsUsed(readFileSync(file, "utf8"))) if (declared[name] !== undefined) used.add(name);

const previous = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));
const tokens = [...used].sort().map((name) => {
  const unit = unitOf(clean(resolve(declared[name])));
  return { name, unit: unit === "other" ? "any" : unit };
});
writeFileSync(join(root, "tokens.json"), `${JSON.stringify({ generatedFrom: GENERATED_FROM, tokens, inferred: previous.inferred ?? [] }, null, 2)}\n`);

// The template type that spells `var(--gcds-${string})` in theme.ts is not a token (it ends in a hyphen).
const pdfUsed = [...varsUsed(readFileSync(join(root, "pdf", "theme.ts"), "utf8"))].filter((name) => !name.endsWith("-"));
const lines = pdfUsed.sort().map((name) => {
  if (declared[name] === undefined) throw new Error(`${name} is read by pdf/theme.ts and not declared by the release`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(clean(resolve(declared[name])))},`;
});
writeFileSync(
  join(root, "pdf", "tokens.generated.ts"),
  `// Generated by scripts/generate-tokens.mjs from ${GENERATED_FROM.package}@${GENERATED_FROM.version} (the pinned release's CSS). Do not edit.\n` +
    `export const GENERATED_FROM = ${JSON.stringify(GENERATED_FROM)} as const;\n` +
    `export const TOKENS: Readonly<Record<string, string>> = {\n${lines.join("\n")}\n};\n`
);
console.log(`tokens.json: ${tokens.length} token(s); pdf/tokens.generated.ts: ${lines.length} value(s)`);
