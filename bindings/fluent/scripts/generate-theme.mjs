#!/usr/bin/env node
// Writes the theme stylesheets a host loads with the Fluent UI binding: theme/<name>.css, one per
// theme object the pinned @fluentui/tokens release exports, each the release's tokens as custom
// properties on the page element (`:root`; the renderer maps it to the form's host inside the shadow
// root). Fluent UI Web Components ship their themes as JavaScript objects (`setTheme(theme)`), not as
// CSS, so these files are the stylesheet form of the same values: nothing is typed by hand.
// Run after a release change:
//   node scripts/generate-theme.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const GENERATED_FROM = { package: "@fluentui/tokens", version: "1.0.0-alpha.24" };
const alias = Object.keys(manifest.devDependencies).find((name) => manifest.devDependencies[name] === `npm:${GENERATED_FROM.package}@${GENERATED_FROM.version}`);
if (!alias) throw new Error("package.json pins no alias for the tokens release");

const loaded = await import(createRequire(join(root, "package.json")).resolve(alias));
// The release resolves to its CommonJS entry, whose exports arrive under `default`.
const tokens = loaded.default ?? loaded;

/** The theme objects written, by file name: Teams' three (what the Teams client draws with) and the web pair. */
const THEMES = {
  "teams-light": "teamsLightTheme",
  "teams-dark": "teamsDarkTheme",
  "teams-high-contrast": "teamsHighContrastTheme",
  "web-light": "webLightTheme",
  "web-dark": "webDarkTheme"
};

// What setTheme() itself refuses: a token name outside the custom-property grammar, or a value that could close the declaration.
const TOKEN_NAME = /^[a-zA-Z_-][a-zA-Z0-9_-]*$/;
const UNSAFE_VALUE = /(;|{|}|\/\*|\*\/|@import|url\s*\(|expression\s*\(|javascript:)/i;

mkdirSync(join(root, "theme"), { recursive: true });
const written = [];
for (const [file, exportName] of Object.entries(THEMES)) {
  const theme = tokens[exportName];
  if (!theme || typeof theme !== "object") throw new Error(`${GENERATED_FROM.package} ${GENERATED_FROM.version} exports no ${exportName}`);
  const lines = [];
  for (const [name, value] of Object.entries(theme)) {
    const text = String(value);
    if (!TOKEN_NAME.test(name)) throw new Error(`${exportName}: token name "${name}" is not a custom property name`);
    if (UNSAFE_VALUE.test(text)) throw new Error(`${exportName}: token ${name} has a value setTheme() would refuse: ${text}`);
    lines.push(`  --${name}: ${text};`);
  }
  const css = `/* Generated by scripts/generate-theme.mjs from ${GENERATED_FROM.package} ${GENERATED_FROM.version}: ${exportName}, ${lines.length} tokens. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;
  writeFileSync(join(root, "theme", `${file}.css`), css);
  written.push({ file: `theme/${file}.css`, theme: exportName, tokens: lines.length });
}
writeFileSync(join(root, "theme", "themes.json"), `${JSON.stringify({ generatedFrom: GENERATED_FROM, themes: written }, null, 2)}\n`);
for (const entry of written) console.log(`${entry.file.padEnd(32)} ${entry.theme.padEnd(24)} ${entry.tokens} tokens`);
